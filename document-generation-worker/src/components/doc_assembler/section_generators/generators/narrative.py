class AssemblyConfig(BaseModel):
    # ── Retrieval knobs ──
    summaries_top_k: int = Field(..., ge=1, description="Refined‑summary docs to fetch for outline.")
    originals_top_k: int = Field(..., ge=1, description="Original raw docs per paragraph.")
    entities_top_k: int = Field(..., ge=0, description="Entity‑extraction docs per paragraph.")
    # ── assembly knobs ──
    paragraphs_count: int = Field(..., ge=1, le=100, description="Number of sections/paragraphs in final document.")
    auto_title: bool = Field(default=True, description="If True, titles generated automatically.")
    titles: Optional[List[Optional[str]]] = Field(default=None, description="Explicit titles (None = auto‑generate).")
    sequential: bool = Field(default=False, description="Generate paragraphs sequentially.")
    restructure: bool = Field(default=True, description="The LLM makes a last pass on the generated paragraph to rewrite them.")
    # ── Prompts ──
    prompt_paragraph: str = Field(..., description="Prompt used to generate each paragraph in non-sequential mode.")
    prompt_sequential_paragraph: str = Field(..., description="Prompt used to generate each paragraph in sequential mode.")
    prompt_restructure: str = Field(..., description="Prompt used to rewrite the whole text at the end to clean it if needed.")


class OutlineParagraph(BaseModel):
    title: str
    query: str


class DocumentOutline(BaseModel):
    """
    The outline we build to guide the document assembly
    """
    problematic: str
    paragraphs: List[OutlineParagraph]


class RefinedParagraph(BaseModel):
    title: str
    content: str
    source_ids: List[str] = []


class RefinedParagraphs(BaseModel):
    """
    The paragraphs generated by the llm
    """
    paragraphs: List[RefinedParagraph]

@SectionGenerator.register("narrative", critical_documents=["refined_summary", "entity_extraction", "original"])
@component
class NarrativeSectionGenerator(SectionGenerator):
    """
    Generates a structured document outline and detailed paragraphs based on refined document summaries.

    This process involves several stages:
        1. **Refined Summaries Retrieval** — Uses the provided subject to retrieve `refined_summaries`, which are summaries of full documents.
        If no subject is specified, all available `refined_summaries` are used to build an overview of the available information.
        2. **Entity Pool Construction** — Builds a pool of all entities found across the documents associated with the document.
        3. **Paragraph assembly** — Based on the document outline, retrieves original text chunks (to minimize hallucination) and relevant entities
        from the pool to generate the document’s paragraphs.

    Two assembly methods are supported:
        - **Independent Paragraphs:** Generate each paragraph separately, then use an LLM to refine and organize the full text.
        - **Sequential Paragraphs:** Generate each paragraph sequentially, providing the previous paragraph as context to the LLM for smoother transitions.
    """

    def __init__(
        self,
        prompt_name: str,
        section: Section,
        document_store: DocumentStore,
        method_parameters: Dict[str, Any],
        document: Optional[AssembledDocument] = None,
        document_writer: Optional[DocumentWriter] = None,
        context: Optional[Dict[str, Any]] = None,
        default_language: str = "English",
        section_heading_prefix: str = "###",
        extract_citations: Optional[bool] = None,
    ):
        SectionGenerator.__init__(
            self,
            prompt_name=prompt_name,
            document_store=document_store,
            section=section,
            document=document,
            document_writer=document_writer,
            context=context,
            method_parameters=method_parameters,
        )

        self.logger = Logger().get_logger("section_generator.narrative")

        # 1. Setup the assembly parameters (subject, titles, ...)
        self.subject = context.get("subject") if context else None

        self.parsed_params = AssemblyConfig(**method_parameters)
        self.logger.debug(f"Parsed parameters: {self.parsed_params}")
        self.context = context or {}

        self.titles_already_decided: List[str] = []
        if not self.parsed_params.auto_title:
            if self.parsed_params.titles:
                for i, title in enumerate(self.parsed_params.titles):
                    if title:
                        self.titles_already_decided.append(f"{i}. {title}")

        self.language = context.get("language", default_language) if context else ""
        self.section_heading_prefix = section_heading_prefix

        # 2. Build the components
        self.retriever = Retriever(document_store=document_store)

        self.outline_generator = StructuredAssembly(
            prompt_name=prompt_name,
            base_model=DocumentOutline,
            fixed_inputs=context
        )

        self.embedder = TextEmbedder()
        self.doc_embedder = DocumentEmbedder()

        self.deduplicator = EntityDeduplicator()

        self.paragraph_generator = TextAssembly(
            prompt_name=self.parsed_params.prompt_paragraph,
            fixed_inputs=context
        )

        self.sequential_paragraph_generator = TextAssembly(
            prompt_name=self.parsed_params.prompt_sequential_paragraph,
            fixed_inputs=context
        )

        self.restructure_generator = StructuredAssembly(
            prompt_name=self.parsed_params.prompt_restructure,
            base_model=RefinedParagraphs,
            fixed_inputs=context
        )

        # 3. Setup the citation pipeline
        self.citation_assembly_pipeline = self._build_citation_assembly_pipeline(
            extract_citations, config.get_current_config(), document_store
        )
    
    def _build_citation_assembly_pipeline(self, extract_citations: Optional[bool], config, document_store: DocumentStore):
        # Initialize citation extraction if enabled
        self.extract_citations = extract_citations
        self.citation_extractor = None

        if extract_citations is None:
            # Read from config
            citation_config = config.citations
            self.extract_citations = citation_config.get("enable_in_documents", True)

        if self.extract_citations:
            try:
                self.citation_extractor = CitationExtractor(document_store=document_store)
                self.logger.info("Citation extraction enabled for this section")
            except Exception as e:
                self.logger.warning(f"Failed to initialize citation extractor: {e}")
                self.citation_extractor = None
        elif self.extract_citations:
            self.logger.warning("Citation extraction requested but citations module not available")
            self.extract_citations = False
    
    @component.output_types(section=List[Section])
    def run(self, sections: Union[List[Section], Section] = []) -> Dict[str, List[Section]]:
        self.logger.info(f"Starting assembly of section '{self.section.name}'")
        self.section.status = SectionStatus.PROCESSING
        self.update_document_section()

        # Optional track the document building with a graph:
        gb = GraphBuilder(graph_file="./logs/document_assembly.html")

        try:
            self.section.source_ids = [] # citation setup

            # Step 1: Generate Outline (Plan in X parts) with the summaries
            document_outline: DocumentOutline = self._generate_outline(gb)

            # Step 2: Setup our entity "pool"
            entity_retriever: Retriever = self._setup_entity_pool()

            # Step 3 : Generate each paragraph
            refined_paragraphs: RefinedParagraphs = self._generate_all_paragraphs(
                document_outline=document_outline, gb=gb, entity_retriever=entity_retriever
            )

            # Step 3.bis : Clean the entity pool
            self._clean_entity_pool()
            
            # Step 4 : Gathering results
            self.section.sections = [
                Section(
                    title=p.title,
                    order=i,
                    name=f"{self.section.name}.{i}",
                    generated_content=p.content,
                    source_ids=p.source_ids
                ) for i, p in enumerate(refined_paragraphs.paragraphs)
            ]

            # Step 4.a : Setting up the offsets for citation extraction
            self.section.section_offsets = []
            current_offset = 0
            for p in refined_paragraphs.paragraphs:
                # Calculate offset of this section in the full generated content
                self.section.section_offsets.append(current_offset)
                # Update current_offset for next section
                section_title_length = len(f"{p.title}\n")
                current_offset += section_title_length + len(p.content)

        except Exception as e:
            gb.save_graph()
            self.section.status = SectionStatus.FAILED
            self.update_document_section()
            self.logger.error(
                f"Error while generating section '{self.section.name}': {e}",
                exc_info=True,
            )
            raise

        finally:
            gb.save_graph()
            self.section = self.update_all_sections_status(status=SectionStatus.COMPLETED, section=self.section)
            self.update_document_section()
            self.logger.info(f"assembly finished for section '{self.section.name}'\nContent: {self.section.generated_content}")
            # Extract citations if enabled
            self.extract_citations_from_sections()

        return {"section": [self.section]}

    def _check_outline(self, outline: DocumentOutline) -> bool:
        """
        Validates that the generated outline meets the expected requirements.

        Args:
            outline: The DocumentOutline to validate

        Returns:
            bool: True if the outline is valid, False otherwise
        """
        # Check paragraph count
        if len(outline.paragraphs) != self.parsed_params.paragraphs_count:
            self.logger.warning(
                f"Outline validation failed: Expected {self.parsed_params.paragraphs_count} paragraphs " +
                f"but got {len(outline.paragraphs)} paragraphs"
            )
            return False

        # Check title requirements if auto_title is False
        if not self.parsed_params.auto_title and self.parsed_params.titles:
            expected_titles = self.parsed_params.titles
            generated_titles = [p.title for p in outline.paragraphs]

            # Check each title that should match
            for i, (expected_title, generated_title) in enumerate(zip(expected_titles, generated_titles)):
                if expected_title and expected_title != generated_title:
                    self.logger.warning(
                        f"Title mismatch at position {i}: Expected '{expected_title}' " +
                        f"but got '{generated_title}'"
                    )
                    return False

        return True
    
    def _generate_outline(self, gb: GraphBuilder) -> DocumentOutline:
        if self.subject:
            summary_docs: List[Document] = self.retriever.run(
                query=self.subject, top_k=self.parsed_params.summaries_top_k, doc_type="refined_summary"
            )["documents"]

        else:
            summary_docs: List[Document] = self.retriever.run(top_k=-1, doc_type="refined_summary")["documents"]

        gb.add_document_nodes(summary_docs)

        document_outline = None
        try_before_fail = 3
        for i in range(try_before_fail):
            self.logger.info(f"Outline assembly try {i}/{try_before_fail}")

            structured_reply = self.outline_generator.run(
                documents=summary_docs,
                inputs={
                    "number_of_sections": str(self.parsed_params.paragraphs_count),
                    "subject": self.subject if self.subject else "",
                    # "persona":"", # Should be in the "context"
                    "titles_already_decided": "\n".join(self.titles_already_decided),
                    "language": self.language
                },
            )["structured_reply"]
            document_outline = DocumentOutline.model_validate(structured_reply)

            if self._check_outline(document_outline):
                break
            else:
                document_outline = None
        if not document_outline:
            raise ValueError(f"Outline assembly failed after {try_before_fail} tries.")

        gb.add_node(id="document_outline", label="document_outline", title=document_outline.model_dump_json(indent=2))
        gb.add_connections(pid=[d.id for d in summary_docs], did=["document_outline"])

        return document_outline

    def _setup_entity_pool(self) -> Retriever:
        entities_docs = self.retriever.run(top_k=-1, doc_type="entity_extraction")["documents"]
        refined_entities = self.deduplicator.deduplicate_documents(docs=entities_docs)
        refined_entities = self.deduplicator.filter_by_LaJ(entities=refined_entities, subject=self.subject)

        self.entity_pool = DocumentStoreProvider().get_store("entity_pooling", require_config_match=False)

        entity_documents = [
            Document(content=entity.model_dump_json(), meta={"type": "refined_entity"}) for entity in refined_entities
        ]
        entity_documents = self.doc_embedder.run(documents=entity_documents)["documents"]
        self.entity_doc_ids = [d.id for d in entity_documents]

        Writer(self.entity_pool).run(entity_documents)

        entity_retriever = Retriever(document_store=self.entity_pool)

        return entity_retriever

    def _clean_entity_pool(self):
        if self.entity_pool:
            if self.entity_doc_ids:
                self.entity_pool.delete_documents(self.entity_doc_ids)
    
    def _generate_all_paragraphs(
        self, document_outline: DocumentOutline, gb: GraphBuilder, entity_retriever: Retriever
    ) -> RefinedParagraphs:
        # 1 : We generate each paragraph one by one
        generated_paragraphs: List[RefinedParagraph] = []
        for paragraph in document_outline.paragraphs:
            if self.parsed_params.sequential:
                generated_paragraph: RefinedParagraph = self._generate_paragraph_core(
                    gb=gb,
                    paragraph=paragraph,
                    entity_retriever=entity_retriever,
                    generator=self.sequential_paragraph_generator,
                    extra_inputs={
                        "previously_generated_paragraphs": generated_paragraphs
                    }
                )
            else:
                generated_paragraph: RefinedParagraph = self._generate_paragraph_core(
                    gb=gb,
                    paragraph=paragraph,
                    entity_retriever=entity_retriever,
                    generator=self.paragraph_generator,
                    extra_inputs=None # No extra inputs needed for non-sequential
                )
            
            generated_paragraphs.append(generated_paragraph)

        if self.parsed_params.restructure:
            # 2 : We make the llm reorganize them
            structured_reply = self.restructure_generator.run(
                inputs={
                    "paragraphs": "\n\n".join([f"Title: {p.title}\nContent:{p.content}" for p in generated_paragraphs]),
                    "min": self.section.num_lines_max,
                    "max": self.section.num_lines_min,
                    "language": self.language,
                    "subject": self.subject
                }
            )["structured_reply"]
            refined_paragraphs: RefinedParagraphs = RefinedParagraphs.model_validate(structured_reply)

            if len(refined_paragraphs.paragraphs) != len(generated_paragraphs):
                self.logger.warning(
                    f"Paragraph restructuring failed: expected {len(generated_paragraphs)} paragraphs " +
                    f"but got {len(refined_paragraphs.paragraphs)} after restructuring. " +
                    f"Subject: '{self.subject}'. " +
                    "This may indicate an issue with the restructuring prompt or the LLM size (hallucination). " +
                    "Falling back to paragraphs generated before restructuring. " +
                    "Tip: try disabling restructuring and enabling sequential assembly in the template."
                )
                refined_paragraphs = RefinedParagraphs(paragraphs=generated_paragraphs)
        else :
            refined_paragraphs = RefinedParagraphs(paragraphs=generated_paragraphs)

        for rp, p in zip(refined_paragraphs.paragraphs, generated_paragraphs): # for citations
            rp.source_ids=p.source_ids

        gb.add_node(id="final", label="final_assembly", title=refined_paragraphs.model_dump_json(indent=2))
        gb.add_connections(pid=[p.content for p in generated_paragraphs], did="final")

        return refined_paragraphs

    def _generate_paragraph_core(
        self, 
        gb: GraphBuilder, 
        paragraph: OutlineParagraph, 
        entity_retriever: Retriever,
        generator: TextAssembly, 
        extra_inputs: Optional[Dict[str, Any]] = None
    ) -> RefinedParagraph:
        # Add paragraph title node to the graph
        gb.add_node(id=paragraph.title, label=paragraph.title, title=paragraph.model_dump_json(indent=2))
        gb.add_connection(pid="document_outline", did=paragraph.title)

        # a. Retrieve original text for our assembly
        original_docs = self.retriever.run(
            query=paragraph.query, 
            top_k=self.parsed_params.originals_top_k, 
            doc_type="original"
        )["documents"]
        gb.add_document_nodes(original_docs)
        gb.add_connections(pid=paragraph.title, did=[d.id for d in original_docs])

        # b. Retrieve the right fully refined entities
        important_entities = entity_retriever.run(
            query=paragraph.query, 
            top_k=self.parsed_params.entities_top_k
        )["documents"]
        gb.add_document_nodes(important_entities)
        gb.add_connections(pid=paragraph.title, did=[d.id for d in important_entities])
        important_entities_objects = self.deduplicator.documents_to_entities(important_entities)

        # c. Generate our paragraph
        inputs = {
            "title": paragraph.title,
            "entities": important_entities_objects,
            "subject": self.subject if self.subject else "",
            "language": self.language,
        }
        if extra_inputs:
            inputs.update(extra_inputs) #Notably : previously generated paragraph if sequential

        generated_paragraph: str = generator.run(
            documents=original_docs, 
            inputs=inputs,
        )["llm_answer"] 

        gb.add_node(id=generated_paragraph, label="Generated Section Uncleaned", title=generated_paragraph, color="#C418A7")
        gb.add_connections(pid=[d.id for d in original_docs + important_entities], did=generated_paragraph)

        return RefinedParagraph(
            title=paragraph.title, 
            content=generated_paragraph, 
            source_ids=[d.id for d in original_docs]
        )

    def extract_citations_from_sections(self):
        if self.extract_citations and self.citation_extractor:
            self.logger.info(f"Extracting citations for section '{self.section.name}'")
            try:
                updated_sections: List[Section] = []
                for sub_section in self.section.sections:
                    updated_sections.append(
                        self.citation_extractor.extract_for_section(
                            section=sub_section, request_id=f"{self.section.job_id}-{self.section.section_id}-{sub_section.section_id}"
                        )
                    )
                self.section.sections = updated_sections
                
                # Update section with citation data
                self.update_document_section()
            except Exception as citation_error:
                self.logger.error(
                    f"Citation extraction failed for section '{self.section.name}': {citation_error}", exc_info=True
                )
                # Don't fail the entire section assembly, just log the error
                self.section.citation_extraction_status = "failed"
                self.update_document_section()
